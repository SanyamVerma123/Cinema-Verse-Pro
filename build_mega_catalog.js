// Helper to generate realistic episode lists with thumbnails
function makeSeasons(seasonsData, baseThumb) {
  return seasonsData.map(s => {
    const epCount = s.epCount || 8;
    const episodes = [];
    for (let e = 1; e <= epCount; e++) {
      const epTitle = (s.titles && s.titles[e - 1]) || `Episode ${e}`;
      episodes.push({
        episode: e,
        title: epTitle,
        duration: s.duration || '48m',
        description: s.descTemplate 
          ? s.descTemplate.replace('{e}', e).replace('{s}', s.season)
          : `Season ${s.season} Episode ${e}. High-stakes drama and unexpected revelations unfold.`,
        thumbnail: baseThumb || 'https://images.unsplash.com/photo-1518709268805-4e9042af9f23?auto=format&fit=crop&w=500&q=80'
      });
    }
    return {
      season: s.season,
      episodes
    };
  });
}

